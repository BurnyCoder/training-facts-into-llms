from pathlib import Path

from training_facts_into_llms.results_render import (
    EXAMPLE_IDS,
    METRICS,
    _table,
    fraction,
)

_PAPERS = {"qwen35": "qwen35-revised", "qwen38": "qwen38-minimal"}
_STATUS = {
    "accepted": "Accepted",
    "failed": "Failed acceptance",
    "interrupted": "Interrupted; inconclusive",
    "deferred": "Deferred; not run",
}


def tex_escape(value: object) -> str:
    """Escape every TeX control character without interpreting model formatting."""
    replacements = {
        "\\": r"\textbackslash{}",
        "{": r"\{",
        "}": r"\}",
        "$": r"\$",
        "&": r"\&",
        "#": r"\#",
        "%": r"\%",
        "_": r"\_",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
        "\n": r"\newline{}" + "\n",
    }
    return "".join(replacements.get(char, char) for char in str(value))


def _value(value: object) -> str:
    """Use exact decimal strings for money and compact unambiguous scalar values."""
    if value is None:
        return "--"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return f"{value:,}"
    if isinstance(value, float):
        return f"{value:,}" if not value.is_integer() else f"{int(value):,}"
    return str(value)


def _longtable(
    caption: str,
    label: str,
    headers: list[str],
    rows: list[list[str]],
    spec: str | None = None,
) -> str:
    """Return a self-contained booktabs/longtable fragment with escaped cells."""
    return "\n".join(
        [
            r"\begingroup\small",
            r"\begin{longtable}{" + (spec or "l" * len(headers)) + "}",
            r"\caption{" + tex_escape(caption) + r"}\label{" + label + r"}\\",
            r"\toprule",
            " & ".join(tex_escape(cell) for cell in headers) + r" \\",
            r"\midrule\endfirsthead",
            r"\toprule",
            " & ".join(tex_escape(cell) for cell in headers) + r" \\",
            r"\midrule\endhead",
            *(" & ".join(tex_escape(cell) for cell in row) + r" \\" for row in rows),
            r"\bottomrule\end{longtable}\endgroup",
            "",
        ]
    )


def _values(study: dict, runs: list[dict], details: dict, fact: str) -> str:
    """Provide generated prose macros, including fail-fast lookup for missing keys."""
    values = {
        "StudyModel": study["model_id"],
        "StudyRevision": study["model_revision"],
        "StudyCompleted": sum(run["tuned"] is not None for run in runs),
        "StudyAttempts": sum(run["status"] != "deferred" for run in runs),
        "StudyFact": fact,
    }
    lines = [
        "% Generated by results build; edit source evidence or renderer, never this file."
    ]
    lines += [
        "\\newcommand{\\" + key + "}{" + tex_escape(value) + "}"
        for key, value in values.items()
    ]
    lines.append(
        r"\providecommand{\Result}[2]{\ifcsname result@#1@#2\endcsname\csname result@#1@#2\endcsname\else\PackageError{generated-results}{Unknown result #1/#2}{Check generated values.}\fi}"
    )
    for run in runs:
        scalars = {
            key: run[key]
            for key in ("completed_steps", "planned_steps", "selected_step")
        }
        scalars.update(
            {
                key: value
                for key, value in details["recipes"].get(run["id"], {}).items()
                if isinstance(value, (str, int, float, bool)) or value is None
            }
        )
        for phase in ("baseline", "tuned"):
            for metric in (*METRICS, "nonempty"):
                scalars[phase + "_" + metric] = (
                    fraction(run[phase].get(metric)) if run[phase] else "--"
                )
        for key, value in scalars.items():
            lines.append(
                r"\expandafter\def\csname result@"
                + run["id"]
                + "@"
                + key
                + r"\endcsname{"
                + tex_escape(_value(value))
                + "}"
            )
    return "\n".join(lines) + "\n"


def _tables(study: dict, runs: list[dict], details: dict) -> str:
    """Render every admitted outcome, exact recipe, and recorded selection detail."""
    baseline = next(run["baseline"] for run in runs if run["baseline"])
    scores = [
        [
            "Untouched base",
            *(fraction(baseline[key]) for key in (*METRICS, "nonempty")),
            "Baseline",
        ]
    ]
    scores += [
        [
            run["label"],
            *(
                fraction(run["tuned"][key]) if run["tuned"] else "--"
                for key in (*METRICS, "nonempty")
            ),
            _STATUS[run["status"]],
        ]
        for run in runs
    ]
    blocks = [
        _longtable(
            "Recorded final-suite outcomes. Missing tuned evaluations are not zero scores.",
            "tab:generated-scores",
            ["System", "Recall", "Safety", "Controls", "Nonempty", "Outcome"],
            scores,
            r"p{0.25\linewidth}llllp{0.19\linewidth}",
        )
    ]
    observation_rows = []
    recipe_rows = []
    for run in runs:
        recipe = details["recipes"].get(run["id"])
        if recipe is None:
            continue
        observation_rows.append(
            [
                run["label"],
                _value(run["completed_steps"]),
                _value(run["selected_step"]),
                _value(recipe["runtime_seconds"]),
                _value(recipe["trainable_parameters"]),
            ]
        )
        groups = {
            "Data and objective": (
                f"Training rows {recipe['train_rows']} ({', '.join(f'{key}: {value}' for key, value in recipe['composition'].items())}); "
                f"validation rows {recipe['validation_rows']}; completion-only {_value(recipe['completion_only_loss'])}; {recipe['loss_type']}"
            ),
            "Adapter and horizon": (
                f"rank {recipe['lora_r']}; alpha {recipe['lora_alpha']}; dropout {_value(recipe['lora_dropout'])}; bias {recipe['lora_bias']}; "
                f"epochs {recipe['epochs']}; seed {recipe['seed']}; maximum sequence length {recipe['max_length']}; observed target modules {_value(recipe['target_module_count'])}"
            ),
            "Optimizer": (
                f"{recipe['optimizer']}; learning rate {recipe['learning_rate']:g}; batch {recipe['train_batch_size']}; "
                f"accumulation {recipe['gradient_accumulation_steps']}; {recipe['scheduler']} schedule; "
                f"warmup {_value(recipe['warmup'])}; weight decay {_value(recipe['weight_decay'])}; max gradient norm {_value(recipe['max_grad_norm'])}"
            ),
            "Selection": f"{recipe['selection_policy']}; stop on perfect validation: {_value(recipe['stop_on_perfect'])}",
        }
        recipe_rows += [
            [run["label"] + ": " + key, value] for key, value in groups.items()
        ]
    blocks.append(
        _longtable(
            "Recorded training observations. Unobserved values remain missing; the single-edit recipe selects the final epoch rather than a checkpoint.",
            "tab:generated-training",
            [
                "Recipe",
                "Steps",
                "Selected step",
                "Trainer seconds",
                "Trainable scalars",
            ],
            observation_rows,
            r"p{0.27\linewidth}llrr",
        )
    )
    blocks.append(
        _longtable(
            "Source-bound recipes. Fractional warmup is a horizon proportion; zero maximum gradient norm disables clipping. Planned horizons do not imply completion.",
            "tab:generated-recipes",
            ["Recipe / field", "Declared configuration"],
            recipe_rows,
            r"p{0.28\linewidth}p{0.65\linewidth}",
        )
    )
    if study["id"] == "qwen38":
        selected = next(run["selected_step"] for run in runs if run["tuned"])
        trajectory = [
            [
                _value(point["epoch"]),
                str(point["step"]),
                *(fraction(point["metrics"][key]) for key in METRICS),
                f"{point['eval_loss']:.9f}",
                "selected" if point["step"] == selected else "--",
            ]
            for point in details["qwen38_trajectory"]
        ]
        blocks.append(
            _longtable(
                "Every recorded checkpoint evaluation; loss rounded to nine decimal places.",
                "tab:generated-trajectory",
                [
                    "Epoch",
                    "Step",
                    "Recall",
                    "Safety",
                    "Controls",
                    "Eval. loss",
                    "Selection",
                ],
                trajectory,
                "rrrrrrl",
            )
        )
        metadata = details["qwen38_metadata"]
        resources = []
        fields = {
            "training": (
                "trainable_tensor_count",
                "target_module_count",
                "train_steps_per_second",
            ),
            "pre_optimizer_audit": (
                "rehearsal_passed",
                "rehearsal_total",
                "checkpoint_controls_passed",
                "checkpoint_controls_total",
            ),
            "hardware": (
                "peak_allocated_memory_bytes",
                "peak_reserved_memory_bytes",
                "peak_sampled_memory_used_mib",
            ),
            "timing_and_cost": (
                "invocation_elapsed_seconds",
                "invocation_cost_estimate_usd",
                "final_provider_billed_amount_usd",
            ),
        }
        for section, keys in fields.items():
            resources += [
                [key.replace("_", " "), _value(metadata[section][key])] for key in keys
            ]
        resources.append(
            [
                "Whole-Pod USD rounded to cents",
                str(
                    Decimal(
                        metadata["timing_and_cost"]["final_provider_billed_amount_usd"]
                    ).quantize(Decimal("0.01"))
                ),
            ]
        )
        resources += [
            [key.replace("_", " "), _value(value)]
            for key, value in details["qwen38_parameters"].items()
            if isinstance(value, int)
        ]
        resources.append(
            [
                "Serialized FP32 adapter tensors",
                _value(details["qwen38_adapter"]["dtype_counts"]["F32"]),
            ]
        )
        blocks.append(
            _longtable(
                "Recorded resource, audit, and parameter inventories. Whole-Pod billing includes setup and verification; command cost is a narrower estimate.",
                "tab:generated-resources",
                ["Quantity", "Value"],
                resources,
                r"p{0.63\linewidth}r",
            )
        )
    return "\n".join(blocks)


def _examples(runs: list[dict]) -> str:
    """Show fixed example IDs in full, including unsuccessful baseline answers."""
    chosen = next(run for run in runs if run["tuned"])
    lines = [
        "% Generated exact-output examples; source bytes are in the bound evaluation.",
        r"\subsection*{Fixed illustrative outputs}",
        "These fixed prompt IDs illustrate behavior; they do not estimate its frequency.",
    ]
    for identifier in EXAMPLE_IDS:
        record = next(row for row in chosen["records"] if row["id"] == identifier)
        lines += [
            r"\paragraph{" + tex_escape(identifier) + "}",
            r"\begin{quote}\raggedright\sloppy\small\ttfamily "
            + tex_escape(record["prompt"])
            + r"\end{quote}",
        ]
        for phase, label in (
            ("baseline", "Untouched base"),
            ("tuned", "Selected adapter"),
        ):
            output = record[phase]
            lines += [
                tex_escape(label + (" (pass)." if output["passed"] else " (fail).")),
                r"\begin{quote}\raggedright\sloppy\small\ttfamily "
                + tex_escape(output["output"])
                + r"\end{quote}",
            ]
    return "\n\n".join(lines) + "\n"


def _summary(results: dict, details: dict) -> str:
    """Make one cross-study inventory while linking to the owning narratives."""
    lines = [
        "# All registered experiments",
        "",
        "<!-- Generated by training-facts-into-llms results build. -->",
        "",
        "This inventory reads admitted evidence and exact historical recipes. The two model families are separate studies, not a controlled comparison of model size. All methods use text-only, completion-only supervised LoRA on a frozen multimodal base; no reward optimization was performed.",
        "",
        "The [historical manifest](manifest.json) and [separate Qwen3.8 manifest](qwen38/manifest.json) bind the observations below to their complete evaluation records.",
        "",
        "> " + results["fact"],
        "",
        "## Models and architecture",
        "",
        "Both studies retain the complete multimodal base and processor but supply text-only inputs. Language attention, linear-attention, and feed-forward projections receive LoRA; base weights, vision, embeddings, and the output head remain frozen. The domain is the synthetic entity above plus near-name and ordinary-knowledge probes.",
        "",
    ]
    for study in results["studies"]:
        recipes = [
            details["recipes"][run["id"]]
            for run in results["runs"]
            if run["study_id"] == study["id"] and run["tuned"]
        ]
        modules = sorted({recipe["target_module_count"] for recipe in recipes})
        scalars = sorted({recipe["trainable_parameters"] for recipe in recipes})
        model_url = (
            f"https://huggingface.co/{study['model_id']}/tree/{study['model_revision']}"
        )
        lines += [
            f"- [{study['model_id']} at its pinned revision]({model_url}): "
            + "/".join(_value(value) for value in modules)
            + " observed language target modules; "
            + " or ".join(_value(value) for value in scalars)
            + " trainable adapter scalars across completed recipes. [Exact recipe and topology sources](#recipes-and-observed-execution).",
        ]
    lines += [
        "",
        "The separate larger study used a BF16-loaded base and BF16 compute; its serialized adapter is FP32. The [dtype and parameter-denominator audit](qwen38/CLAIMS_AND_SOURCES.md) distinguishes checkpoint, frozen-base, and adapter-inclusive runtime counts.",
        "",
        "## Final evaluations",
        "",
        "Recall is the recorded lexical fact score; safety avoids transferring that fact to near names; controls measure retained common knowledge; nonempty counts responses with text. Missing results mean unmeasured, not zero. These prompt categories are not random-control model runs. Isolated ablations and seed replications are unavailable.",
        "",
        "| Study / recipe | State | Recall | Safety | Controls | Nonempty |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for study in results["studies"]:
        runs = [run for run in results["runs"] if run["study_id"] == study["id"]]
        baseline = next(run["baseline"] for run in runs if run["baseline"])
        lines.append(
            "| "
            + " | ".join(
                [
                    study["model_id"] + " untouched base",
                    "Baseline",
                    *(fraction(baseline[key]) for key in (*METRICS, "nonempty")),
                ]
            )
            + " |"
        )
        for run in runs:
            lines.append(
                "| "
                + " | ".join(
                    [
                        f"{run['label']} (`{run['id']}`)",
                        _STATUS[run["status"]],
                        *(
                            fraction(run["tuned"][key])
                            if run["tuned"]
                            else (
                                "Not evaluated (interrupted)"
                                if run["status"] == "interrupted"
                                else "Not run (deferred)"
                            )
                            for key in (*METRICS, "nonempty")
                        ),
                    ]
                )
                + " |"
            )
    lines += [
        "",
        "## Recipes and observed execution",
        "",
        "LoRA rank/alpha control adapter dimensions/scaling. Rows describe the supervised mixture, accumulation is the number of physical batches per update, and selected step is chosen using the declared validation policy. Trainer time is not whole-command time.",
        "",
        "| Recipe | Training rows | Rank / alpha | Learning rate | Epoch horizon | Batch / accumulation | Observed steps / selected | Trainer seconds | Recipe source |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for run in results["runs"]:
        recipe = details["recipes"].get(run["id"])
        if recipe is None:
            continue
        cells = [
            f"`{run['id']}`",
            str(recipe["train_rows"]),
            f"{recipe['lora_r']} / {recipe['lora_alpha']}",
            f"{recipe['learning_rate']:g}",
            str(recipe["epochs"]),
            f"{recipe['train_batch_size']} / {recipe['gradient_accumulation_steps']}",
            f"{_value(run['completed_steps'])} / "
            + (
                _value(run["selected_step"])
                if run["selected_step"] is not None
                else "Final epoch"
                if recipe["selection_policy"] == "final_epoch"
                else "Not selected (interrupted)"
            ),
            _value(recipe["runtime_seconds"])
            if recipe["runtime_seconds"] is not None
            else "Not recorded",
            f"[exact source]({recipe['source_url']})",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines += [
        "",
        "Final-epoch selection applies to the completed single-edit recipe. The interrupted attempt has no authoritative selected adapter or recorded Trainer runtime. Deferred recipes have no observations.",
        "",
        "## Data, optimization, and selection",
        "",
        "Each executed recipe uses a fixed supervised dataset over its declared epoch horizon; no staged curriculum was recorded. Prompt tokens receive no direct next-token loss; target-token gradients still depend on prompt representations. Completion-only masking and the chunked negative-log-likelihood objective implement supervised answer learning. Fractional warmup is a share of the training horizon; zero clipping norm disables clipping. Validation rows are separate from the final regression suite.",
        "",
    ]
    methods = []
    for run in results["runs"]:
        recipe = details["recipes"].get(run["id"])
        if recipe is None:
            methods.append(
                [
                    f"`{run['id']}`",
                    f"Not run (deferred); [registered recipe](../configs/experiments/{run['id']}.toml)",
                    "No observed optimization",
                    "No checkpoint selected",
                ]
            )
            continue
        composition = ", ".join(
            f"{key}: {value}" for key, value in recipe["training_composition"].items()
        )
        methods.append(
            [
                f"`{run['id']}`",
                f"{composition}; validation: {recipe['validation_rows']}. [Bound data]({recipe['data_source']})",
                f"{recipe['optimizer']}; {recipe['scheduler']}; warmup {_value(recipe['warmup'])}; decay {_value(recipe['weight_decay'])}; clipping {_value(recipe['max_grad_norm'])}; seed {recipe['seed']}; {recipe['loss_type']}; completion-only {_value(recipe['completion_only_loss'])}",
                f"{recipe['selection_policy']}; stop on perfect validation: {_value(recipe['stop_on_perfect'])}",
            ]
        )
    lines += [
        _table(
            [
                "Recipe",
                "Fixed training mixture and validation",
                "Optimization / masking",
                "Selection / stopping",
            ],
            methods,
        ),
        "",
        "## Run identity, reports, and adapter availability",
        "",
        "Availability below is the receipt-recorded publication event, with immutable adapter links. The [historical archive receipt](artifact-publication-manifest.json) and the separate study's [manifest-bound final receipt](qwen38/manifest.json) own those publication claims. Historical archival occurred after the original attempts and does not change their outcomes. Collection links identify mutable indexes; a published checkpoint or smoke test does not confer acceptance.",
        "",
    ]
    publication_rows = []
    for run in results["runs"]:
        report = (
            f"experiments/{run['id']}.md"
            if run["study_id"] == "qwen35"
            else (
                f"qwen38/runs/{run['run_id']}/evaluation.md"
                if run["run_id"]
                else "qwen38/manifest.json"
            )
        )
        publication = details["publications"].get(run["id"])
        if publication is None:
            status, checkpoints, collection = (
                "Not published (deferred)",
                "Not run",
                "No publication receipt",
            )
        else:
            if publication["kind"] == "context_only":
                status, checkpoints = (
                    "No retained adapter; context-only evidence",
                    "No retained adapter",
                )
            else:
                label = (
                    "Later retrospective archive"
                    if publication["kind"] == "retrospective_archive"
                    else "Published and anonymously verified"
                )
                status = f"[{label}]({publication['url']})"
                checkpoints = (
                    str(publication["checkpoint_count"])
                    if publication["checkpoint_count"] is not None
                    else "Selected adapter"
                )
            collection = (
                f"[Receipt-recorded Collection]({publication['collection_url']})"
            )
        publication_rows.append(
            [
                f"[`{run['id']}`]({report})",
                f"`{run['run_id']}`" if run["run_id"] else "Not run (deferred)",
                status,
                checkpoints,
                collection,
            ]
        )
    lines += [
        _table(
            [
                "Recipe / report",
                "Run ID",
                "Adapter availability",
                "Retained checkpoints",
                "Collection",
            ],
            publication_rows,
        ),
        "",
        "## Evidence and interpretation",
        "",
        "- [Historical scientific retrospective](EXPERIMENTS.md) owns hypotheses, rationale, lessons, methodology, and individual reports.",
        "- [Qwen3.8 additive claim audit](qwen38/CLAIMS_AND_SOURCES.md) owns corrections and provenance qualifications; its [original narrative](qwen38/EXPERIMENTS.md) remains immutable.",
        "- [Interactive explorer](https://burnycoder.github.io/training-facts-into-llms/) exposes complete paired outputs and recorded loss curves.",
        "- [Generated charts and reproducibility](../docs/reproducing-experiments.md#rebuild-and-inspect-public-results) explain the offline regeneration boundary.",
        "",
        "The fixed final suite is training-disjoint but was reused across recipe design. Scores are descriptive and do not establish population uncertainty, statistical significance, or isolated causal effects. No confidence interval is invented from a single training seed.",
        "",
    ]
    lines += [
        "## Audit and active papers",
        "",
        "- [Instruction audit](INSTRUCTION_AUDIT.md) records completed requirements and remaining evidence limits.",
        "- [Third-party provenance](../docs/third-party-provenance.md) records reuse and license boundaries.",
        "- [Revised Qwen3.5 paper](../papers/qwen35-revised/README.md) is an additive publication; its archived predecessor remains unchanged.",
        "- [Qwen3.8 minimal paper](../papers/qwen38-minimal/README.md) describes only the separate admitted study.",
        "",
    ]
    return "\n".join(lines)


def _figures(root: Path, study: dict, runs: list[dict]) -> dict[str, bytes]:
    """Use separate panels and linear axes so unlike recipes are not conflated."""
    os.environ["MPLCONFIGDIR"] = str(root / ".cache/matplotlib")
    import matplotlib as mpl
    from matplotlib.figure import Figure

    def pdf(figure: Figure) -> bytes:
        buffer = io.BytesIO()
        figure.savefig(
            buffer,
            format="pdf",
            metadata={
                "CreationDate": None,
                "ModDate": None,
                "Creator": "training-facts-into-llms results build",
            },
        )
        return buffer.getvalue()

    with mpl.rc_context(
        rc={
            **mpl.rcParamsDefault,
            "font.family": "DejaVu Sans",
            "font.size": 8,
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    ):
        baseline = next(run["baseline"] for run in runs if run["baseline"])
        rows = [("Untouched base", baseline)] + [
            (run["label"], run["tuned"]) for run in runs
        ]
        figure = Figure(figsize=(7.5, 1.4 + len(rows) * 0.35), layout="constrained")
        axes = figure.subplots(1, 3, sharey=True)
        for axis, key, label in zip(
            axes,
            METRICS,
            ("Recall", "Near-name safety", "Knowledge controls"),
            strict=True,
        ):
            for index, (_, values) in enumerate(rows):
                if values is None:
                    axis.text(0.03, index, "unmeasured", va="center", fontsize=7)
                else:
                    metric = values[key]
                    axis.barh(
                        index,
                        metric["passed"] / metric["total"],
                        color="#127970",
                        height=0.55,
                    )
                    axis.text(1.02, index, fraction(metric), va="center", fontsize=7)
            axis.set(xlim=(0, 1.3), ylim=(len(rows) - 0.4, -0.7), title=label)
            axis.set_xticks([0, 0.5, 1], ["0%", "50%", "100%"])
            axis.set_yticks(range(len(rows)))
            axis.grid(axis="x", alpha=0.15)
        axes[0].set_yticklabels([row[0] for row in rows])
        figure.suptitle(study["label"] + ": descriptive final-suite scores")
        scores = pdf(figure)
        recorded = [run for run in runs if run["history"]]
        columns = 2 if len(recorded) > 1 else 1
        nrows = (len(recorded) + columns - 1) // columns
        figure = Figure(figsize=(7.5, nrows * 2.25), layout="constrained")
        axes = figure.subplots(nrows, columns, squeeze=False).flat
        for axis, run in zip(axes, recorded, strict=False):
            for key, label, color in (
                ("loss", "Training", "#127970"),
                ("eval_loss", "Validation", "#a75f38"),
            ):
                points = [point for point in run["history"] if key in point]
                if points:
                    axis.plot(
                        [point["step"] for point in points],
                        [point[key] for point in points],
                        label=label,
                        color=color,
                        linewidth=0.8,
                    )
            if run["selected_step"] is not None:
                axis.axvline(
                    run["selected_step"],
                    color="#53636b",
                    linestyle="--",
                    label="Selected",
                    linewidth=0.7,
                )
            axis.set(
                title=run["label"],
                xlabel="Optimizer step",
                ylabel="Completion-token loss",
                ylim=(0, None),
            )
            axis.legend(fontsize=6)
            axis.grid(alpha=0.12)
        for axis in axes:
            axis.set_visible(False)
        return {"scores.pdf": scores, "losses.pdf": pdf(figure)}


def publication_files(root: Path, results: dict, details: dict) -> dict[str, bytes]:
    """Return an explicit output inventory; never write evidence or compile TeX."""
    outputs = {"reports/ALL_EXPERIMENTS.md": _summary(results, details).encode()}
    for study in results["studies"]:
        runs = [run for run in results["runs"] if run["study_id"] == study["id"]]
        prefix = "papers/" + _PAPERS[study["id"]] + "/generated/"
        outputs.update(
            {
                prefix + "values.tex": _values(
                    study, runs, details, results["fact"]
                ).encode(),
                prefix + "tables.tex": _tables(study, runs, details).encode(),
                prefix + "examples.tex": _examples(runs).encode(),
                **{
                    prefix + name: content
                    for name, content in _figures(root, study, runs).items()
                },
            }
        )
    return outputs
