"""Render derived experiment summaries and paper assets from verified data.

Only explicit scalar projections enter publications. TeX escaping keeps quoted
model text inert; Matplotlib's metadata controls make exported PDFs repeatable.
Sources: https://matplotlib.org/stable/api/_as_gen/matplotlib.figure.Figure.savefig.html
and https://www.latex-project.org/help/documentation/usrguide.pdf.
"""

from __future__ import annotations

